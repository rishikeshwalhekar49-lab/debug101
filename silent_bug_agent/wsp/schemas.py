"""Data contracts and schemas for Weight-Space Programming (WSP)."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Callable, Dict, List, Optional, Tuple


class WeightAnomalyType(str, Enum):
    RANK_COLLAPSE = "rank_collapse"              # Effective rank << min(rows, cols)
    ILL_CONDITIONED = "ill_conditioned"          # Condition number > 1e4
    DEAD_DIRECTION = "dead_direction"            # Dominant projection causes activation death
    BIAS_COLLAPSE = "bias_collapse"              # Extreme bias pushing activations negative/saturated
    WEIGHT_OUTLIER = "weight_outlier"            # High kurtosis / extreme outlier weights (reasoning loops)
    NAN_INF = "nan_inf"                          # Non-finite parameter values
    FROZEN_OR_ZERO = "frozen_or_zero"            # All-zero or non-updating weights
    SPECTRAL_EXPLOSION = "spectral_explosion"    # Spectral norm (max singular value) too large


class WeightSurgeryType(str, Enum):
    SUBSPACE_EXCISION = "subspace_excision"      # W' = W(I - v v^T) removing degenerate direction
    LOW_RANK_DELTA = "low_rank_delta"            # W' = W + alpha * (u v^T)
    BIAS_CENTER = "bias_center"                  # Re-centering bias vectors
    OUTLIER_CLAMP = "outlier_clamp"              # Clamping kurtosis outliers
    NEURON_RESET = "neuron_reset"                # Re-initializing or orthogonalizing dead neurons
    SPECTRAL_SCALE = "spectral_scale"            # Normalizing/regularizing spectral norm


@dataclass
class WeightFinding:
    """Anomalous pattern or failure mode identified directly in weight space."""
    layer_name: str
    param_shape: Tuple[int, ...]
    anomaly_type: WeightAnomalyType
    severity: str                                # "critical" | "warning" | "info"
    metric_value: float                          # e.g. condition number, effective rank, max bias
    threshold: float
    message: str
    evidence: Dict[str, Any] = field(default_factory=dict)
    suggested_action: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "layer_name": self.layer_name,
            "param_shape": list(self.param_shape),
            "anomaly_type": self.anomaly_type.value,
            "severity": self.severity,
            "metric_value": self.metric_value,
            "threshold": self.threshold,
            "message": self.message,
            "evidence": self.evidence,
            "suggested_action": self.suggested_action,
        }


@dataclass
class WeightReport:
    """Aggregated weight-space perception report across all model layers."""
    model_name: str
    total_parameters: int
    trainable_parameters: int
    findings: List[WeightFinding] = field(default_factory=list)
    layer_summaries: Dict[str, Dict[str, Any]] = field(default_factory=dict)
    diagnostics: List[str] = field(default_factory=list)

    @property
    def has_critical(self) -> bool:
        return any(f.severity == "critical" for f in self.findings)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "model_name": self.model_name,
            "total_parameters": self.total_parameters,
            "trainable_parameters": self.trainable_parameters,
            "findings": [f.to_dict() for f in self.findings],
            "layer_summaries": self.layer_summaries,
            "diagnostics": self.diagnostics,
        }


@dataclass
class WeightPatch:
    """A surgical weight modification candidate generated by the Weight Editor."""
    target_param: str
    surgery_type: WeightSurgeryType
    description: str
    params_affected: int
    pct_affected: float                          # e.g. 0.016%
    original_norm: float
    new_norm: float
    delta_norm: float
    meta: Dict[str, Any] = field(default_factory=dict)
    # The actual tensor transformation function: takes original tensor -> returns patched tensor
    transform_fn: Optional[Callable[[Any], Any]] = field(default=None, repr=False)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "target_param": self.target_param,
            "surgery_type": self.surgery_type.value,
            "description": self.description,
            "params_affected": self.params_affected,
            "pct_affected": round(self.pct_affected, 4),
            "original_norm": round(self.original_norm, 4),
            "new_norm": round(self.new_norm, 4),
            "delta_norm": round(self.delta_norm, 4),
            "meta": self.meta,
        }


@dataclass
class DualSolution:
    """Unified solution candidate combining Code AST diff and/or Weight Patches."""
    title: str
    rationale: str
    confidence: float
    origin: str                                  # "code" | "weight" | "hybrid"
    code_diff: Optional[str] = None
    weight_patches: List[WeightPatch] = field(default_factory=list)
    iteration: int = 1
    feedback_history: List[str] = field(default_factory=list)

    @property
    def has_code_diff(self) -> bool:
        return bool(self.code_diff and self.code_diff.strip())

    @property
    def has_weight_patches(self) -> bool:
        return len(self.weight_patches) > 0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "title": self.title,
            "rationale": self.rationale,
            "confidence": self.confidence,
            "origin": self.origin,
            "code_diff": self.code_diff,
            "weight_patches": [wp.to_dict() for wp in self.weight_patches],
            "iteration": self.iteration,
            "feedback_history": self.feedback_history,
        }

